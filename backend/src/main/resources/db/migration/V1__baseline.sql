-- V1 — Schéma de référence (baseline) d'AMAME.
--
-- Origine : schéma créé par Hibernate (ddl-auto=update) à partir des entités, sur PostgreSQL 15,
-- puis extrait avec « pg_dump --schema-only --no-owner --no-privileges ». C'est le schéma
-- qu'Hibernate gérait seul jusqu'à l'étape 1 de la migration Neon/Bunny.
--
-- Comportement de Flyway (spring.flyway.baseline-on-migrate=true, baseline-version=1) :
--   - base existante sans historique Flyway (production) : elle est marquée « en V1 »,
--     ce script n'y est PAS exécuté ;
--   - base vide (tests, nouvelle base de développement, branche) : ce script est exécuté.
--
-- Ne jamais modifier ce fichier : toute évolution du schéma passe par un nouveau script V2, V3…
-- Par rapport à la sortie de pg_dump, seuls ont été retirés les réglages de session (SET …,
-- search_path) et les lignes « \restrict » : ils resteraient actifs pour les migrations suivantes.

--
